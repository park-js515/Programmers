WITH C AS (
    SELECT
        (SELECT SUM(CODE) FROM SKILLCODES WHERE CATEGORY = 'Front End') AS FRONT_END,
        (SELECT SUM(CODE) FROM SKILLCODES WHERE NAME = 'Python') AS P,    
        (SELECT SUM(CODE) FROM SKILLCODES WHERE NAME = 'C#') AS CS
),
    CTE AS (
    SELECT
        CASE
            WHEN SKILL_CODE & C.FRONT_END > 0 AND SKILL_CODE & C.P > 0 THEN 'A'
            WHEN SKILL_CODE & C.CS > 0 THEN 'B'
            WHEN SKILL_CODE & C.FRONT_END > 0 THEN 'C'
        END AS GRADE,
        ID,
        EMAIL
    FROM DEVELOPERS, C
)

SELECT *
FROM CTE
WHERE GRADE IS NOT NULL
ORDER BY GRADE, ID